create or replace function public.audit_critical_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.audit_log(actor_type, actor_id, action, entity_type, entity_id, metadata)
  values (
    'database',
    null,
    lower(tg_op),
    tg_table_name,
    coalesce((to_jsonb(new)->>'id'), (to_jsonb(old)->>'id')),
    jsonb_build_object(
      'changed_at', now(),
      'old', case when tg_op in ('UPDATE','DELETE') then to_jsonb(old) - array['cpf','email','telefone','data_nascimento'] else null end,
      'new', case when tg_op in ('INSERT','UPDATE') then to_jsonb(new) - array['cpf','email','telefone','data_nascimento'] else null end
    )
  );
  return coalesce(new, old);
end;
$$;
revoke all on function public.audit_critical_change() from public;
grant execute on function public.audit_critical_change() to service_role;

do $$
begin
