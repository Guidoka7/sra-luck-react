create or replace function public.dequeue_webhook_events(p_limit integer default 25)
returns setof public.webhook_queue
language plpgsql
security definer
set search_path = public
as $$
begin
  return query
  with picked as (
    select q.id
    from public.webhook_queue q
    where q.status = 'pendente'
      and q.next_attempt_at <= now()
      and (q.locked_at is null or q.locked_at < now() - interval '10 minutes')
    order by q.created_at
    for update skip locked
    limit greatest(1, least(coalesce(p_limit, 25), 100))
  )
  update public.webhook_queue q
  set status = 'processando',
      attempts = q.attempts + 1,
      locked_at = now(),
      updated_at = now()
  from picked
  where q.id = picked.id
  returning q.*;
end;
$$;
revoke all on function public.dequeue_webhook_events(integer) from public, anon, authenticated;
grant execute on function public.dequeue_webhook_events(integer) to service_role;

