create or replace function public.check_rate_limit(p_key text, p_limit integer, p_window_seconds integer)
returns table(allowed boolean, remaining integer, retry_after_seconds integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_now timestamptz := clock_timestamp();
  v_start timestamptz;
  v_count integer;
  v_window integer := greatest(1, least(coalesce(p_window_seconds, 60), 86400));
  v_limit integer := greatest(1, least(coalesce(p_limit, 60), 10000));
begin
  if p_key is null or char_length(p_key) = 0 or char_length(p_key) > 200 then
    raise exception 'RATE_LIMIT_KEY_INVALID';
  end if;

  insert into public.rate_limit_buckets(key, window_started_at, hit_count, updated_at)
  values (p_key, v_now, 1, v_now)
  on conflict (key) do update
  set window_started_at = case
        when public.rate_limit_buckets.window_started_at + make_interval(secs => v_window) <= v_now then v_now
        else public.rate_limit_buckets.window_started_at
      end,
      hit_count = case
        when public.rate_limit_buckets.window_started_at + make_interval(secs => v_window) <= v_now then 1
        else public.rate_limit_buckets.hit_count + 1
      end,
      updated_at = v_now
  returning window_started_at, hit_count into v_start, v_count;

  allowed := v_count <= v_limit;
  remaining := greatest(0, v_limit - v_count);
  retry_after_seconds := greatest(1, ceil(extract(epoch from (v_start + make_interval(secs => v_window) - v_now)))::integer);
  return next;
end;
$$;
revoke all on function public.check_rate_limit(text, integer, integer) from public, anon, authenticated;
grant execute on function public.check_rate_limit(text, integer, integer) to service_role;

