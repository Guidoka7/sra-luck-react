-- 002_20260911_rate_limit_webhook_queue
-- O que: rate limit distribuído e fila durável de webhooks.
-- Por quê: evitar brute force/spam e não perder eventos externos quando um Worker falhar.
-- Quem usa: middleware do Worker e cron do Cloudflare.
