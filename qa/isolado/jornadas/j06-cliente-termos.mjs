// J06 — cliente (QA-02 Bruna) escolhe a forma de quitação e agenda os termos pelo app
import { abrir } from "./lib.mjs";
import { loginCliente, aba } from "./clientelogin.mjs";
import { writeFileSync } from "node:fs";
const T = process.env.SP_TXT || "/tmp";
const { page, shot, fim, rede } = await abrir("J06-cliente-forma-e-termos", { mobile: true });
const r = {};
r.login = await loginCliente(page, "90000000256", "20/03/1988");
await aba(page, "Agenda"); await shot("agenda");
writeFileSync(`${T}/j06-agenda.txt`, await page.locator("body").innerText());
await page.getByRole("button", { name: "Escolher forma de pagamento" }).first().click(); await page.waitForTimeout(1200);
await shot("formas");
writeFileSync(`${T}/j06-formas.txt`, await page.locator("body").innerText());
await page.locator("button").filter({ hasText: /^\s*PIX/ }).last().click(); await page.waitForTimeout(600);
await shot("pix-selecionado");
r.botaoConfirmarForma = await page.locator("button").last().innerText().catch(() => "");
const botoesSheet = await page.locator("button").evaluateAll(els => els.map(e => e.innerText.trim()).filter(Boolean));
r.sheet = botoesSheet.slice(-3);
const forma = page.waitForResponse((res) => res.request().method() === "POST" && res.url().includes("/api/cliente/"), { timeout: 20000 });
await page.locator("button").filter({ hasText: /Confirmar|Continuar|PIX$/i }).last().click();
const rf = await forma; r.forma = { status: rf.status(), path: new URL(rf.url()).pathname, body: (await rf.text()).slice(0, 300) };
await page.waitForTimeout(2000); await shot("apos-forma");
writeFileSync(`${T}/j06-apos-forma.txt`, await page.locator("body").innerText());
r.diasHabilitadosSet = await page.locator("button:not([disabled])").evaluateAll(els => els.map(e => e.innerText.trim()).filter(t => /^\d+$/.test(t)));
await page.locator("button").filter({ hasText: /^›$/ }).first().click(); await page.waitForTimeout(800);
r.diasHabilitadosOut = await page.locator("button:not([disabled])").evaluateAll(els => els.map(e => e.innerText.trim()).filter(t => /^\d+$/.test(t)));
await shot("outubro");
await page.locator("button:not([disabled])").filter({ hasText: /^\s*5\s*$/ }).first().click(); await page.waitForTimeout(1000);
await shot("dia-5");
writeFileSync(`${T}/j06-dia.txt`, await page.locator("body").innerText());
await page.locator("button").filter({ hasText: /^10:00$/ }).first().click(); await page.waitForTimeout(800);
await shot("horario-10h");
r.aposHorario = (await page.locator("button").evaluateAll(els => els.map(e => e.innerText.trim()).filter(Boolean))).slice(-6);
const ag = page.waitForResponse((res) => res.request().method() === "POST" && res.url().includes("/api/cliente/agendar"), { timeout: 20000 });
await page.locator("button").filter({ hasText: /Confirmar|Agendar/i }).last().click();
await page.waitForTimeout(700);
const conf2 = page.locator("button").filter({ hasText: /Confirmar|Agendar/i }).last();
const rag = await Promise.race([ag, page.waitForTimeout(2500).then(() => null)]) || (await conf2.click(), await ag);
r.agendar = { status: rag.status(), body: (await rag.text()).slice(0, 300) };
await page.waitForTimeout(2000); await shot("termos-agendados");
writeFileSync(`${T}/j06-final.txt`, await page.locator("body").innerText());
await page.reload({ waitUntil: "domcontentloaded" }); await page.waitForTimeout(3000);
await aba(page, "Agenda"); await shot("apos-reload");
writeFileSync(`${T}/j06-reload.txt`, await page.locator("body").innerText());
r.botoes = await page.locator("button").evaluateAll(els => els.map(e => (e.innerText || e.getAttribute("aria-label") || "").trim().replace(/\s+/g, " ")).filter(Boolean).filter(t => !/^\d+$/.test(t)));
await fim(r);
console.log(JSON.stringify(r, null, 1));
