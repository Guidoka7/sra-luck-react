// J02 — login da equipe, fila de validação, abrir comprovante (PDF do Storage) e confirmar a parcela
import { abrir, BASE, CREDS, sql } from "./lib.mjs";
import { writeFileSync } from "node:fs";
const T = process.env.SP_TXT || "/tmp";
const { page, context, shot, fim, rede } = await abrir("J02-equipe-validacao-comprovante");
const r = {};
await page.goto(`${BASE}/admin/visao-geral`, { waitUntil: "domcontentloaded" }); await page.waitForTimeout(1500);
r.semSessao = page.url(); await shot("admin-sem-sessao");
await page.goto(`${BASE}/admin/login`, { waitUntil: "domcontentloaded" }); await page.waitForTimeout(1000);
r.inputs = await page.locator("input").evaluateAll(els => els.map(e => [e.type, e.placeholder, e.name]));
await page.locator('input[type="email"]').fill(CREDS.QA_ADMIN_EMAIL);
await page.locator('input[type="password"]').fill(CREDS.QA_ADMIN_PASSWORD);
await shot("login-equipe");
await page.getByRole("button", { name: /Entrar|Acessar/ }).first().click();
await page.waitForTimeout(3000); r.aposLogin = page.url(); await shot("visao-geral");
await page.goto(`${BASE}/admin/financeiro/avancado?aba=validacao`, { waitUntil: "domcontentloaded" }); await page.waitForTimeout(3000);
await shot("fila-validacao");
writeFileSync(`${T}/j02-fila.txt`, await page.locator("body").innerText());
await page.getByRole("button", { name: "VALIDAR" }).first().click();
await page.waitForTimeout(1500); await shot("modal-validar");
writeFileSync(`${T}/j02-modal.txt`, await page.locator("body").innerText());
const [aba] = await Promise.all([context.waitForEvent("page"), page.getByRole("link", { name: "Abrir comprovante em nova aba" }).click()]);
const resp = await aba.waitForEvent("response", { timeout: 15000 }).catch(() => null);
await aba.waitForTimeout(1500);
r.comprovante = { url: aba.url().replace(/token=[^&]+/, "token=<redacted>"), status: resp?.status(), contentType: resp?.headers()["content-type"] };
await aba.screenshot({ path: `${process.env.EVDIR}/05-comprovante-aberto.png` }).catch(() => {});
await aba.close();
const href = await page.getByRole("link", { name: "Abrir comprovante em nova aba" }).getAttribute("href");
const direto = await context.request.get(`${BASE}${href}`, { maxRedirects: 0 });
r.comprovanteApi = { href, status: direto.status(), location: (direto.headers()["location"] || "").replace(/token=[^&]+/, "token=<redacted>").slice(0, 160), contentType: direto.headers()["content-type"] };
const semSessao = await (await import("playwright")).request.newContext();
const anon = await semSessao.get(`${BASE}${href}`, { maxRedirects: 0 });
r.comprovanteSemSessao = anon.status(); await semSessao.dispose();
await page.locator("textarea").first().fill("Validação QA isolado — comprovante fictício conferido.").catch(() => {});
const conf = page.waitForResponse((res) => res.request().method() !== "GET" && res.url().includes("/api/admin/") && !res.url().includes("monitoramento"), { timeout: 20000 });
await page.getByRole("button", { name: "CONFIRMAR RECEBIMENTO" }).click();
await page.waitForTimeout(500); await shot("confirmacao-dupla");
await page.getByRole("button", { name: /Confirmar ação/i }).click();
const rc = await conf; r.confirmar = { status: rc.status(), path: new URL(rc.url()).pathname, body: (await rc.text()).slice(0, 400) };
await page.waitForTimeout(2000); await shot("apos-confirmar");
r.botoes = await page.locator("button, a").evaluateAll(els => els.map(e => (e.innerText || e.getAttribute("aria-label") || "").trim().replace(/\s+/g, " ")).filter(Boolean));
await fim(r);
console.log(JSON.stringify(r, null, 1));
console.log(rede.map(x => `${x.method} ${x.path} ${x.status}`).join("\n"));
